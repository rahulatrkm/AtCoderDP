    print()
    print("The magic of rerooting:")
    print()
    print("  Instead of recomputing EVERYTHING for each root (O(N²)),")
    print("  we INCREMENTALLY adjust the answer as we move the root around!")
    print()
    print("  • dp1[child] = subtree values (computed once)")
    print("  • parent_contribution = dynamically computed as we reroot")
    print("  • Total time: O(N) - each edge visited twice (once each direction)")
    print()
