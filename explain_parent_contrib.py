    print("    for child in adj[node]:")
    print("        if child != parent:")
    print("            prod *= dp1[child]  # Add all children")
    print("    ans[node] = prod")
    print()
    print("    # 2. Reroot to each child")
    print("    for child in adj[node]:")
    print("        if child != parent:")
    print("            # Calculate what THIS node contributes when child is root")
    print("            remaining = parent_contribution")
    print("            for other_child in adj[node]:")
    print("                if other_child != parent and other_child != child:")
    print("                    remaining *= dp1[other_child]")
    print()
    print("            node_contribution = 1 + remaining")
    print("            dfs2(child, node, node_contribution)")
    print()
    
    print("=" * 80)
    print("KEY INSIGHT")
