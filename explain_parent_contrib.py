    print("=" * 80)
    print()
    print("When rerooting from PARENT to CHILD:")
    print()
    print("  parent_contribution = 1 + (parent's_parent_contrib * other_children)")
    print()
    print("  where other_children = all of parent's children EXCEPT the current child")
